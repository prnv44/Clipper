"""Safe local storage for setup settings and source inputs."""
from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path

from .. import config
from .settings import MANAGED_KEYS, SECRET_KEYS, path_value


# Keep starters in the package: installed wheels do not include repo templates.
_SOURCE_STARTERS = (
    (
        "CHANNELS_FILE", "channels.txt",
        "# Add one YouTube channel URL or @handle per line.\n"
        "# Optional settings after |: limit=5 min_views=100000 scan=0\n"
        "# Inactive example (replace with your own channel and remove #):\n"
        "# https://www.youtube.com/@example | limit=5\n"
        "# After adding channels, run `ziv make`.\n",
    ),
    (
        "LINKS_FILE", "links.txt",
        "# Add one video URL or local file path per line.\n"
        "# Optional settings after |: clips=5 min=10 max=45 style=clean\n"
        "# Inactive examples (replace with your own sources and remove #):\n"
        "# https://www.youtube.com/watch?v=VIDEO_ID | clips=5 | min=10 max=45 | style=clean\n"
        "# /path/to/video.mp4\n"
        "# After adding sources, run `ziv make`. Processed lines are marked '# DONE'.\n",
    ),
)


class SetupStorageError(RuntimeError):
    """A local setup file could not be read or written safely."""


def read_env(path: Path | None = None) -> dict[str, str]:
    """Read key/value metadata from a dotenv file without executing it."""
    path = Path(path or config.ENV_FILE)
    if not path.exists():
        return {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise SetupStorageError(f"Cannot read local configuration: {exc}") from exc

    values: dict[str, str] = {}
    for raw_line in lines:
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        key, separator, raw_value = line.partition("=")
        if not separator or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key.strip()):
            continue
        values[key.strip()] = config._dotenv_value(raw_value)
    return values


def _env_quote(value: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9_./:@+,-]*", value):
        return value
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _safe_chmod(path: Path) -> None:
    try:
        path.chmod(0o600)
    except OSError:
        # chmod is not available or meaningful on some Windows filesystems.
        pass


def write_env(values: dict[str, str], path: Path | None = None) -> Path:
    """Atomically replace the dotenv file and restrict it to the owner."""
    path = Path(path or config.ENV_FILE)
    lines = [
        "# Ziv local configuration. Keep this file private.",
        "# Generated by `ziv setup`; values are read by the next Ziv process.",
    ]
    for key in sorted(values):
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            continue
        lines.append(f"{key}={_env_quote(str(values[key]))}")
    content = "\n".join(lines) + "\n"

    temporary: Path | None = None
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
        temporary = Path(name)
        try:
            os.fchmod(fd, 0o600)
        except (AttributeError, OSError):
            # Windows Python may not expose fchmod; the final chmod remains
            # best-effort after the atomic replace.
            pass
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        _safe_chmod(path)
        return path
    except OSError as exc:
        if temporary is not None:
            try:
                temporary.unlink(missing_ok=True)
            except OSError:
                pass
        raise SetupStorageError(f"Cannot save local configuration: {exc}") from exc


def initialize_source_files(values: dict[str, str]) -> None:
    """Create inactive starters only when missing; never read existing inputs."""
    for key, filename, content in _SOURCE_STARTERS:
        path = Path(path_value(values.get(key, filename), config.PROJECT_ROOT))
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            try:
                # Exclusive creation also protects files/symlinks that appear
                # concurrently; no existence-check/overwrite race is possible.
                handle = path.open("x", encoding="utf-8", newline="\n")
            except FileExistsError:
                if not path.is_file():
                    raise OSError("the path exists but is not a regular file")
                continue
            try:
                with handle:
                    handle.write(content)
                    handle.flush()
                    os.fsync(handle.fileno())
            except OSError:
                # An incomplete new starter must not prevent repair on retry.
                try:
                    path.unlink()
                except OSError:
                    pass
                raise
        except (OSError, ValueError) as exc:
            raise SetupStorageError(
                f"Cannot initialize {key} at {path}: {exc}. "
                "Check the path and directory permissions, then run `ziv setup` again."
            ) from exc


def redacted_value(key: str, value: str) -> str:
    if key in SECRET_KEYS:
        return "<set; hidden>" if value else "<not set>"
    return value if value else "<empty>"


def settings_for_display(values: dict[str, str]) -> list[tuple[str, str]]:
    """Return managed settings in stable order, with credentials redacted."""
    return [(key, redacted_value(key, values.get(key, ""))) for key in MANAGED_KEYS]


def validate_cookie_file_metadata(value: str) -> tuple[bool, str]:
    """Validate only cookie path metadata; never opens or parses the file."""
    if not value.strip():
        return True, ""
    path = Path(value).expanduser()
    try:
        if not path.exists():
            return False, "cookie file does not exist"
        if not path.is_file():
            return False, "cookie path is not a regular file"
        if not os.access(path, os.R_OK):
            return False, "cookie file is not readable"
    except OSError:
        return False, "cookie file metadata could not be checked"
    return True, ""


